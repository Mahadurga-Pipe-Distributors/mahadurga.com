// Restore stored preferences (theme-init.js already set the data attrs,
// but we still need to sync button states and apply translations)
(function init() {
  const storedLang  = localStorage.getItem('mdp-lang')  || 'en';
  const storedTheme = localStorage.getItem('mdp-theme') || '';

  // Sync lang buttons to stored/default
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === storedLang);
  });

  // Apply translations if non-default
  if (storedLang !== 'en') applyTranslations(storedLang);

  // Ensure data-theme attr is set (default = light)
  if (!storedTheme) document.documentElement.setAttribute('data-theme', 'light');
})();
